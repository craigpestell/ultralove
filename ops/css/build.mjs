// Trims Martfury's style.css to the selectors used by the collected pages and scripts. See README.md.
import { PurgeCSS } from 'purgecss';
import fs from 'fs';
import { minify } from 'csso';
const states = ['open','opened','active','show','shown','hover','selected','current','current-menu-item','current-menu-ancestor','loading','loaded','displayed','visible','fixed','sticky','focus','error','invalid','disabled','processing','added','in','out','fade','collapse','collapsing','collapsed','hide','hidden','expanded','is-active','has-children','menu-item-has-children','no-js','js','yes-js','js_active','rtl','touch','mobile','scrolled','minimized','closed','done','success','wc-block','added_to_cart'];
const r = await new PurgeCSS().purge({
  content: ['work/html/*.html', 'work/dom/*.html', 'work/js/*.js'],
  css: ['../../wp-content/themes/martfury/style.css'],
  fontFace: false, keyframes: false, variables: false,
  rejected: true,
  safelist: {
    standard: states,
    deep: [/^slick/, /^pswp/, /^mfp/, /^ui-/, /tooltip/, /^nprogress/, /^notify/, /select2/, /^pp_/, /^yith/, /^blockUI/, /^blockOverlay/, /^blockMsg/, /^woocommerce-(error|message|info|notice|NoticeGroup)/, /^star-rating/, /^stars/],
    greedy: [/slick/, /pswp/, /tooltip/, /mfp/, /flex-/, /^gform/, /^ginput/, /^gfield/, /select2/]
  }
});
const out = r[0];
const OUT = '../../wp-content/themes/martfury-child/css/martfury-trimmed.css';
// @charset has to stay the very first thing in the file, so the note goes after it.
const min = minify(out.css).css.replace(/^@charset "UTF-8";/, '');
fs.writeFileSync(OUT, '@charset "UTF-8";\n/* Generated by ops/css/build.mjs from the parent theme\'s style.css - do not edit; see ops/css/README.md. */\n' + min);
fs.writeFileSync('work/rejected.txt', (out.rejected || []).join('\n'));
const orig = fs.readFileSync('../../wp-content/themes/martfury/style.css','utf8');
console.log('original', Math.round(orig.length/1024),'KB | trimmed', Math.round(out.css.length/1024),'KB | minified', Math.round(fs.statSync(OUT).size/1024),'KB | rejected selectors', (out.rejected||[]).length);
