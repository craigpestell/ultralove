// Trims the site's big stylesheets to the selectors used by the collected pages and scripts. See README.md.
// Each target is written to the child theme's css/ folder and swapped in under its own handle by the child
// functions.php (ultralove_use_trimmed_styles()).
import { PurgeCSS } from 'purgecss';
import fs from 'fs';
import { execFileSync } from 'child_process';
import { minify } from 'csso';

const THEMES = '../../wp-content/themes';
const OUT_DIR = `${THEMES}/martfury-child/css`;

// Also kept whatever the samples show: states WooCommerce's scripts add on interaction (the log-in
// password eye's revealed state, the product gallery's zoom trigger) and tags that only appear in
// editor content (hr).
const alwaysKeep = ['hr', 'display-password', 'show-password-input', 'woocommerce-product-gallery__trigger'];
const states = ['open','opened','active','show','shown','hover','selected','current','current-menu-item','current-menu-ancestor','loading','loaded','displayed','visible','fixed','sticky','focus','error','invalid','disabled','processing','added','in','out','fade','collapse','collapsing','collapsed','hide','hidden','expanded','is-active','has-children','menu-item-has-children','no-js','js','yes-js','js_active','rtl','touch','mobile','scrolled','minimized','closed','done','success','wc-block','added_to_cart'];
const safelist = {
  standard: [...states, ...alwaysKeep],
  deep: [/^slick/, /^pswp/, /^mfp/, /^ui-/, /tooltip/, /^nprogress/, /^notify/, /select2/, /^pp_/, /^yith/, /^blockUI/, /^blockOverlay/, /^blockMsg/, /^woocommerce-(error|message|info|notice|NoticeGroup)/, /^star-rating/, /^stars/],
  greedy: [/slick/, /pswp/, /tooltip/, /mfp/, /flex-/, /^gform/, /^ginput/, /^gfield/, /select2/]
};

// Vendor plugins aren't in git: their CSS comes from dev, and the trimmed copy's file name carries the plugin
// version it was made from, so a plugin update falls back to the original until this is rerun.
function fromDev(path) {
  return execFileSync('ssh', ['ultralove-dev-app', `cat /var/www/html/${path}`], { encoding: 'utf8', maxBuffer: 64 << 20 });
}
function devPluginVersion(slug) {
  return execFileSync('ssh', ['ultralove-dev-app', `cd /var/www/html && sudo -u www-data wp plugin get ${slug} --field=version --skip-themes 2>/dev/null`], { encoding: 'utf8' }).trim();
}

// url()s in the original are relative to its own folder; the copy lives in the child theme's css/.
const rebase = (css, base) => css.replace(/url\(\s*(['"]?)(?!data:|https?:|\/|#)([^'")]+)\1\s*\)/g, (m, q, u) => `url(${q}${base}${u}${q})`);

const wcVersion = devPluginVersion('woocommerce');
const targets = [
  { name: 'martfury', from: "the parent theme's style.css", css: fs.readFileSync(`${THEMES}/martfury/style.css`, 'utf8'), out: 'martfury-trimmed.css', charset: true },
  { name: 'ionicons', from: "the parent theme's css/ionicons.min.css", css: rebase(fs.readFileSync(`${THEMES}/martfury/css/ionicons.min.css`, 'utf8'), '../../martfury/css/'), out: 'ionicons-trimmed.css' },
  { name: 'eleganticons', from: "the parent theme's css/eleganticons.min.css", css: rebase(fs.readFileSync(`${THEMES}/martfury/css/eleganticons.min.css`, 'utf8'), '../../martfury/css/'), out: 'eleganticons-trimmed.css' },
  { name: 'font-awesome', from: "the parent theme's css/font-awesome.min.css", css: rebase(fs.readFileSync(`${THEMES}/martfury/css/font-awesome.min.css`, 'utf8'), '../../martfury/css/'), out: 'font-awesome-trimmed.css' },
  { name: 'woocommerce-general', from: `WooCommerce ${wcVersion}'s assets/css/woocommerce.css (from dev)`, css: rebase(fromDev('wp-content/plugins/woocommerce/assets/css/woocommerce.css'), '/wp-content/plugins/woocommerce/assets/css/'), out: `woocommerce-${wcVersion}-trimmed.css`, stale: /^woocommerce-.*-trimmed\.css$/ },
];

fs.mkdirSync('work', { recursive: true });
for (const t of targets) {
  const [out] = await new PurgeCSS().purge({
    content: ['work/html/*.html', 'work/dom/*.html', 'work/js/*.js'],
    css: [{ raw: t.css }],
    fontFace: false, keyframes: false, variables: false,
    rejected: true,
    safelist,
  });
  // A copy made from another plugin version is no longer used (the version is in the name); drop it.
  if (t.stale) for (const f of fs.readdirSync(OUT_DIR)) if (t.stale.test(f) && f !== t.out) fs.rmSync(`${OUT_DIR}/${f}`);
  const note = `/* Generated by ops/css/build.mjs from ${t.from} - do not edit; see ops/css/README.md. */\n`;
  let min = minify(out.css).css;
  // @charset has to stay the very first thing in the file, so the note goes after it.
  if (t.charset) min = '@charset "UTF-8";\n' + note + min.replace(/^@charset "UTF-8";/, '');
  else min = note + min.replace(/^@charset "UTF-8";/, '');
  fs.writeFileSync(`${OUT_DIR}/${t.out}`, min);
  fs.writeFileSync(`work/rejected-${t.name}.txt`, (out.rejected || []).join('\n'));
  console.log(`${t.name.padEnd(20)} ${String(Math.round(t.css.length / 1024)).padStart(4)} KB -> ${String(Math.round(min.length / 1024)).padStart(4)} KB  ${t.out}  (${(out.rejected || []).length} selectors removed)`);
}
