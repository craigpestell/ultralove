// One page render can fail on its own (Chrome dropping the connection, a slow response); try it again.
// Each try has an overall time limit: some Chrome calls (a screenshot, an evaluate) have no timeout of their
// own and can hang for good, which froze a whole CI run with all workers waiting.
const TRY_LIMIT = 5 * 60 * 1000;
async function retry(fn, tries = 3) {
	for (let i = 1; ; i++) {
		let timer;
		try {
			return await Promise.race([
				fn(),
				new Promise((_, reject) => { timer = setTimeout(() => reject(new Error(`no result after ${TRY_LIMIT / 60000} minutes`)), TRY_LIMIT); }),
			]);
		} catch (e) {
			if (i >= tries) {
				log(`giving up after ${tries} tries: ${e.message}`);
				throw e;
			}
			log(`retrying (${i}/${tries - 1}): ${e.message}`);
			await new Promise((r) => setTimeout(r, 2000));
		} finally {
			clearTimeout(timer);
		}
	}
}

async function pool(items, fn) {
	let i = 0;
	await Promise.all(Array.from({ length: CONCURRENCY }, async () => { while (i < items.length) await fn(items[i++]); }));
}

async function main() {
	if (!CHROME) throw new Error('Chrome not found; set CHROME');
	fs.rmSync(WORK, { recursive: true, force: true });
	fs.mkdirSync(WORK, { recursive: true });
	const tunnel = await openTunnel();
	// Chrome is restarted if it goes away (it occasionally drops the connection mid-render).
	let browser = null, launching = null;
	const chrome = async () => {
		if (browser && browser.connected) return browser;
		// Pages rendered side by side count as background tabs, which Chrome throttles - on GitHub's runners a
		// screenshot of one could then hang (Page.captureScreenshot timed out). A stuck call fails after a minute.
		launching ??= puppeteer.launch({
			executablePath: CHROME,
			headless: true,
			protocolTimeout: 60000,
			args: ['--no-sandbox', '--hide-scrollbars', '--disable-background-timer-throttling', '--disable-renderer-backgrounding', '--disable-backgrounding-occluded-windows'],
		})
			.then((b) => { browser = b; return b; })
			.finally(() => { launching = null; });
		return launching;
	};
	try {
		const jobs = [];
		// Logged out only: signed-in visitors get the full stylesheet up front (34-critical-css.php).
		for (const p of PAGES) for (const vp of VIEWPORTS) jobs.push({ path: p, vp, cookie: null, name: `${vp.name} ${p}` });

		const results = [];
		let done = 0;
		log(`collecting: ${PAGES.length} pages x ${VIEWPORTS.length} sizes, JavaScript off and on = ${jobs.length * 2} renders`);
		await pool(jobs.flatMap((j) => [{ ...j, js: false }, { ...j, js: true }]), async (job) => {
			try {
				results.push(await retry(async () => collect(await chrome(), tunnel.port, job)));
			} catch (e) {
				throw new Error(`${job.name} (js ${job.js ? 'on' : 'off'}): ${e.message}`);
			}
			log(`collect ${String(++done).padStart(3)}/${jobs.length * 2}  ${job.name} (js ${job.js ? 'on' : 'off'})`);
		});

		const { css, stats } = build(results);
		log(`requests: ${fetchStats.tunnel} through the tunnel, ${fetchStats.cached} static files answered from memory`);
		log(`critical CSS: ${stats.rules} of ${stats.of} rules, ${stats.faces} @font-face, ${stats.keyframes} @keyframes, ${Math.round(css.length / 1024)} KB`);
		fs.writeFileSync(path.join(WORK, 'critical.css'), css);
		if (css.length > SIZE_LIMIT) throw new Error(`critical CSS is ${Math.round(css.length / 1024)} KB, over the ${SIZE_LIMIT / 1024} KB limit`);

		// The same as the committed file: nothing to ship, so nothing to check.
		if (!args.pages && fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === HEADER + css + '\n') {
			log('critical CSS unchanged from the committed file - nothing to check or write');
			return;
		}

		if (!args['no-verify']) {
			const pageCssHash = new Map(results.filter((r) => !r.job.js).map((r) => [r.job.name, r.cssHash]));
			log(`checking: each page's first screen with only the critical CSS vs the full CSS, ${jobs.length} pages`);
			const rows = await verify(chrome, tunnel.port, jobs, css, pageCssHash);
			const report = rows.map((r) => `${r.pct.toFixed(2).padStart(6)}%  ${r.name}`).join('\n');
			fs.writeFileSync(path.join(WORK, 'verify.txt'), report + '\n');
			console.log('first-screen difference, critical CSS only vs full CSS (worst first):\n' + rows.slice(0, 12).map((r) => `${r.pct.toFixed(2).padStart(6)}%  ${r.name}`).join('\n'));
			const bad = rows.filter((r) => r.pct > DIFF_LIMIT);
			if (bad.length) throw new Error(`${bad.length} page(s) differ by more than ${DIFF_LIMIT}% - see ops/critical-css/work/*-diff.png; critical.css not updated`);
		}

		// Only a full run (every page type) replaces the theme's file; --pages runs are for a look at work/.
		if (args.pages) {
			log('--pages given: the theme file is left alone; the result is in work/critical.css');
			return;
		}
		fs.writeFileSync(OUT, HEADER + css + '\n');
		log(`wrote ${path.relative(process.cwd(), OUT)}`);
	} finally {
		if (browser) await browser.close().catch(() => {});
		tunnel.close();
	}
}

main().catch((e) => { console.error(e.message); process.exit(1); });
